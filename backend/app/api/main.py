"""FastAPI application.

Run:  cd backend && uvicorn app.api.main:app --host 0.0.0.0 --port 8000   (or double-click start_app.bat)
App:  http://localhost:8000        (the upload page, app/web/)
Docs: http://localhost:8000/docs  (interactive Swagger UI generated by FastAPI)

Endpoints (all under /api/v1):
    GET  /health                       models loaded? which device?
    POST /detect/image                 upload an image -> report (synchronous, ~2-6 s on CPU)
    POST /detect/video                 upload a video  -> job id (processed in the background)
                                       both accept an optional form field remove_rain=true
    GET  /jobs/{job_id}                job status / progress / run_id when done
    GET  /results/{run_id}             the stored violation report (JSON)
    GET  /files/{run_id}/{filename}    download annotated image/video, evidence and plate crops
"""
from __future__ import annotations

import json
import logging
import re
import shutil
import uuid
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from app import __version__
from app.api.jobs import JobManager
from app.config import get_settings
from app.core.exceptions import HelmetDetectionError, InvalidMediaError, ModelLoadError
from app.core.logging_config import setup_logging
from app.services.detection_service import DetectionService
from app.services.media import IMAGE_EXT, VIDEO_EXT, media_kind

log = logging.getLogger(__name__)
state: dict = {"service": None, "error": None, "jobs": None}
SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]+")
RUN_ID = re.compile(r"^[0-9]{8}-[0-9]{6}-[0-9a-f]{6}$")


@asynccontextmanager
async def lifespan(app: FastAPI):
    settings = get_settings()
    setup_logging(settings.log_dir)
    try:
        state["service"] = await run_in_threadpool(DetectionService, settings)   # loads all models once
    except ModelLoadError as e:
        state["error"] = str(e)
        log.error("models not loaded: %s", e)
    state["jobs"] = JobManager()
    yield
    state["jobs"].shutdown()


app = FastAPI(title="Smart Helmet Detection API", version=__version__, lifespan=lifespan)
app.add_middleware(CORSMiddleware, allow_origins=["http://localhost:5173", "http://localhost:3000",
                                                  "http://127.0.0.1:5173"],
                   allow_methods=["*"], allow_headers=["*"])


def _service() -> DetectionService:
    if state["service"] is None:
        raise HTTPException(503, f"models are not loaded: {state['error']}")
    return state["service"]


async def _save_upload(file: UploadFile, allowed: set[str]) -> Path:
    settings = get_settings()
    name = SAFE_NAME.sub("_", Path(file.filename or "upload").name)
    if Path(name).suffix.lower() not in allowed:
        raise HTTPException(415, f"unsupported file type; allowed: {sorted(allowed)}")
    dest = settings.upload_dir / f"{uuid.uuid4().hex[:8]}_{name}"
    limit, size = settings.max_upload_mb * 1024 * 1024, 0
    with dest.open("wb") as f:
        while chunk := await file.read(1024 * 1024):
            size += len(chunk)
            if size > limit:
                f.close()
                dest.unlink(missing_ok=True)
                raise HTTPException(413, f"file larger than {settings.max_upload_mb} MB")
            f.write(chunk)
    return dest


@app.exception_handler(InvalidMediaError)
async def _invalid_media(_, exc: InvalidMediaError):
    from fastapi.responses import JSONResponse
    return JSONResponse(status_code=422, content={"detail": str(exc)})


@app.exception_handler(HelmetDetectionError)
async def _pipeline_error(_, exc: HelmetDetectionError):
    from fastapi.responses import JSONResponse
    log.exception("pipeline error")
    return JSONResponse(status_code=500, content={"detail": str(exc)})


@app.get("/api/v1/health")
def health():
    s = state["service"]
    return {"status": "ok" if s else "error", "version": __version__,
            "device": s.pipeline.device.name if s else None, "error": state["error"]}


def _force(remove_rain: bool) -> frozenset[str]:
    """User-requested enhancement steps (rain removal is manual - see enhancement.is_rainy)."""
    return frozenset({"rain"}) if remove_rain else frozenset()


@app.post("/api/v1/detect/image")
async def detect_image(file: UploadFile = File(...), remove_rain: bool = Form(False),
                       read_all_plates: bool = Form(False)):
    service = _service()
    path = await _save_upload(file, IMAGE_EXT)
    return await run_in_threadpool(service.process_image, path, _force(remove_rain), read_all_plates)


@app.post("/api/v1/detect/video", status_code=202)
async def detect_video(file: UploadFile = File(...), remove_rain: bool = Form(False)):
    service = _service()
    path = await _save_upload(file, VIDEO_EXT)
    media_kind(path)
    force = _force(remove_rain)
    return state["jobs"].submit(path, lambda p, progress: service.process_video(p, progress, force)).to_dict()


@app.get("/api/v1/jobs/{job_id}")
def job_status(job_id: str):
    job = state["jobs"].get(job_id)
    if job is None:
        raise HTTPException(404, "job not found")
    return job.to_dict()


@app.get("/api/v1/results/{run_id}")
def result(run_id: str):
    if not RUN_ID.match(run_id):
        raise HTTPException(400, "invalid run id")
    path = get_settings().report_dir / f"{run_id}.json"
    if not path.exists():
        raise HTTPException(404, "result not found")
    return json.loads(path.read_text(encoding="utf-8"))


@app.get("/api/v1/files/{run_id}/{filename}")
def download(run_id: str, filename: str):
    if not RUN_ID.match(run_id) or SAFE_NAME.search(filename) or filename.startswith("."):
        raise HTTPException(400, "invalid path")
    path = get_settings().output_dir / run_id / filename          # no '..' possible after the checks above
    if not path.is_file():
        raise HTTPException(404, "file not found")
    return FileResponse(path, filename=filename, content_disposition_type="inline")


# The web page (upload -> results). Mounted last so every /api/v1 route above takes priority.
WEB_DIR = Path(__file__).resolve().parents[1] / "web"
if WEB_DIR.is_dir():
    app.mount("/", StaticFiles(directory=WEB_DIR, html=True), name="web")
